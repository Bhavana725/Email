class CppAnalyzer:
    CONTROL_KEYWORDS = {
        'if', 'for', 'while', 'switch', 'do', 'else', 'case', 'catch',
        'return', 'sizeof', 'delete', 'throw', 'break', 'continue', 'goto'
    }

    def __init__(self):
        self.function_defs = {}           # func_name -> (start_line, end_line, code)
        self.function_calls = defaultdict(set)  # func_name -> set(called_func_names)
        self.includes = {}                # include_file -> line_number
        self.used_includes = set()
        self.structure_tree = []
        self.function_complexity = {}
        self.optimized_code_saved = False  # Flag to track if optimized code is saved

    def analyze_file(self, filename):
        try:
            with open(filename, 'r') as f:
                code = f.read()
        except FileNotFoundError:
            print(f"Error: File '{filename}' not found.")
            return

        cleaned_code = self._remove_comments_and_strings(code)
        lines = code.split('\n')

        # 1. Analyze includes
        self._analyze_includes(code)

        # 2. Analyze function definitions and calls
        self._analyze_functions_and_calls(cleaned_code, lines)

        # 3. Build call graph and find used functions starting from main()
        used_functions = self._find_used_functions()

        # 4. Find unused functions/includes
        unused_functions = set(self.function_defs) - used_functions
        unused_includes = set(self.includes) - self.used_includes

        # 5. Print unused items
        print("UNUSED INCLUDES:")
        for inc in unused_includes:
            print(f"  {inc} (line {self.includes[inc]})")
        print("\nUNUSED FUNCTIONS:")
        for func in unused_functions:
            print(f"  {func} (line {self.function_defs[func][0]})")

        # 6. Analyze complexity (but don't re-analyze after saving)
        if not self.optimized_code_saved:
            self._analyze_complexity(lines)
            print("\n--- COMPLEXITY REPORT ---")
            for func, info in self.function_complexity.items():
                print(f"Function '{func}':")
                print(f"  Time Complexity: {info['time_complexity']}")
                print(f"  Space Complexity: {info['space_complexity']}")
                if info['loops']:
                    print("  Loops:")
                    for loop_line in info['loops']:
                        print(f"    Loop at line {loop_line}")
                if info['recursion']:
                    print("  Recursion detected.")
                if info['components']:
                    print("  Complexity Breakdown:")
                    for comp in info['components']:
                        print(f"    - {comp}")

        # 7. Remove unused code and save optimized code only once
        optimized_code = self._remove_unused_code(code, unused_includes, unused_functions)
        self._save_optimized_code(optimized_code, filename)

        # 8. Generate and save structure tree
        self._generate_structure_tree(lines, filename)

        # Mark that the optimized code has been saved
        self.optimized_code_saved = True

        # Return results, but no further analysis will happen after this
        return {
            "unused_includes": [f"{inc} (line {self.includes[inc]})" for inc in unused_includes],
            "unused_functions": [f"{func} (line {self.function_defs[func][0]})" for func in unused_functions],
            "complexity": self.function_complexity,
            "structure_tree": self.structure_tree,
        }

    def _remove_comments_and_strings(self, code):
        code = re.sub(r'//.*', '', code)
        code = re.sub(r'/\*.*?\*/', '', code, flags=re.DOTALL)
        code = re.sub(r'"(?:\\.|[^"\\])*"', '""', code)
        code = re.sub(r"'(?:\\.|[^'\\])*'", "''", code)
        return code

    def _analyze_includes(self, code):
        for i, line in enumerate(code.split('\n')):
            m = re.match(r'\s*#include\s*[<"]([^>"]+)[>"]', line)
            if m:
                self.includes[m.group(1)] = i+1

    def _analyze_functions_and_calls(self, code, lines):
        func_def_pattern = re.compile(
            r'^[ \t]*(?:[\w:<>]+[ \t*]+)+([a-zA-Z_][a-zA-Z0-9_]*)[ \t]*\(([^)]*)\)[ \t]*(const)?[ \t]*\{', re.MULTILINE)
        for m in func_def_pattern.finditer(code):
            func_name = m.group(1)
            if func_name in self.CONTROL_KEYWORDS:
                continue
            start_line = code[:m.start()].count('\n') + 1
            brace_count = 0
            end_line = start_line
            for idx, line in enumerate(lines[start_line-1:], start=start_line):
                brace_count += line.count('{')
                brace_count -= line.count('}')
                if brace_count == 0:
                    end_line = idx
                    break
            func_code = '\n'.join(lines[start_line-1:end_line])
            self.function_defs[func_name] = (start_line, end_line, func_code)

        call_pattern = re.compile(r'([a-zA-Z_][a-zA-Z0-9_]*)\s*\(')
        for i, line in enumerate(lines):
            for m in call_pattern.finditer(line):
                func_name = m.group(1)
                if func_name in self.CONTROL_KEYWORDS:
                    continue
                for def_func, (start, end, _) in self.function_defs.items():
                    if start <= i+1 <= end:
                        self.function_calls[def_func].add(func_name)
                        break
                if 'main' in self.function_defs and not any(start <= i+1 <= end for start, end, _ in self.function_defs.values()):
                    self.function_calls['main'].add(func_name)

                if func_name in ['printf', 'scanf', 'fopen', 'fclose']:
                    self.used_includes.add('stdio.h')
                elif func_name in ['cout', 'cin']:
                    self.used_includes.add('iostream')
                elif func_name in ['strlen', 'strcpy', 'strcat', 'strcmp']:
                    self.used_includes.add('string.h')
                elif func_name in ['memcpy', 'memset', 'memcmp']:
                    self.used_includes.add('memory.h')

    def _find_used_functions(self):
        used = set()
        queue = deque()
        if 'main' in self.function_defs:
            queue.append('main')
        else:
            return set(self.function_defs)

        while queue:
            func = queue.popleft()
            if func in used:
                continue
            used.add(func)
            for callee in self.function_calls.get(func, []):
                if callee in self.function_defs and callee not in used:
                    queue.append(callee)
        return used

    def _analyze_complexity(self, lines):
        for func, (start, end, func_code) in self.function_defs.items():
            time_complexity = "O(1)"
            space_complexity = "O(1)"  # Default unless something changes
            loop_lines = []
            recursion = False
            max_depth = self._max_loop_depth(func_code)
            components = []

            if max_depth > 0:
                time_complexity = f"O(n^{max_depth})" if max_depth > 1 else "O(n)"
                components.append("loops")
                for idx, line in enumerate(func_code.split('\n'), start=start):
                    if re.search(r'\bfor\b|\bwhile\b', line):
                        loop_lines.append(idx)

            if re.search(rf'\b{func}\s*\(', func_code):
                recursion = True
                components.append("recursion")
                if time_complexity == "O(1)":
                    time_complexity = "O(n)"

            self.function_complexity[func] = {
                'time_complexity': time_complexity,
                'space_complexity': space_complexity,
                'loops': loop_lines,
                'recursion': recursion,
                'components': components
            }

    def _max_loop_depth(self, code):
        tokens = re.findall(r'\b(for|while)\b|[{}]', code)
        max_depth = 0
        current_depth = 0
        stack = []
        for token in tokens:
            if token in ('for', 'while'):
                current_depth += 1
                stack.append('loop')
                max_depth = max(max_depth, current_depth)
            elif token == '{':
                stack.append('{')
            elif token == '}':
                while stack:
                    popped = stack.pop()
                    if popped == 'loop':
                        current_depth -= 1
                        break
        return max_depth

    def _remove_unused_code(self, code, unused_includes, unused_functions):
        lines = code.split('\n')
        for inc in unused_includes:
            for i, line in enumerate(lines):
                if '#include' in line and inc in line:
                    lines[i] = ''
        for func in unused_functions:
            start, end, _ = self.function_defs[func]
            for i in range(start-1, end):
                lines[i] = ''
        return '\n'.join(lines)

    def _save_optimized_code(self, optimized_code, filename):
        optimized_filename = f"optimised_{filename}"
        with open(optimized_filename, 'w') as f:
            f.write(optimized_code)
        print(f"Optimized code saved to '{optimized_filename}'.")

    def _generate_structure_tree(self, lines, filename):
        structure_tree_filename = f"structure_tree_{filename}.txt"
        with open(structure_tree_filename, 'w') as f:
            for func, (start, end, _) in self.function_defs.items():
                f.write(f"Function: {func}, Start: {start}, End: {end}\n")
            for inc, line in self.includes.items():
                f.write(f"Include: {inc}, Line: {line}\n")
        print(f"Code structure saved to '{structure_tree_filename}'.")

