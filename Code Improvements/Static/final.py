class PythonComplexityAnalyzer(ast.NodeVisitor):
    def __init__(self):
        self.current_function = None
        self.function_complexity = {}
        self.function_details = defaultdict(list)
        self.nested_level = 0
        self.loop_stack = []
        self.space_complexity = defaultdict(lambda: "O(1)")

    def visit_FunctionDef(self, node):
        self.current_function = node.name
        self.function_complexity[self.current_function] = ("O(1)", [])
        self.space_complexity[self.current_function] = "O(1)"
        self.nested_level = 0
        self.loop_stack = []
        self.generic_visit(node)
        self.current_function = None

    def visit_For(self, node):
        if self.current_function:
            self.nested_level += 1
            loop_info = {
                'type': 'for',
                'variable': getattr(node.target, 'id', '?'),
                'iter': ast.unparse(node.iter),
                'line': node.lineno,
                'nested_level': self.nested_level
            }
            self.loop_stack.append(loop_info)
            self._update_function_complexity("n", loop_info)
            self.generic_visit(node)
            self.nested_level -= 1
            self.loop_stack.pop()

    def visit_While(self, node):
        if self.current_function:
            self.nested_level += 1
            loop_info = {
                'type': 'while',
                'condition': ast.unparse(node.test),
                'line': node.lineno,
                'nested_level': self.nested_level
            }
            self.loop_stack.append(loop_info)
            self._update_function_complexity("n", loop_info, condition=ast.unparse(node.test))
            self.generic_visit(node)
            self.nested_level -= 1
            self.loop_stack.pop()

    def visit_Call(self, node):
        if self.current_function:
            func_name = None
            if isinstance(node.func, ast.Name):
                func_name = node.func.id
            elif isinstance(node.func, ast.Attribute):
                func_name = node.func.attr

            call_complexity_val = "1"
            suggestion = None

            if func_name in ['sort', 'sorted']:
                call_complexity_val = 'n log n'
                suggestion = "Consider if sorting is necessary..."
            elif func_name in ['sum', 'min', 'max', 'len', 'any', 'all']:
                call_complexity_val = 'n'
                suggestion = "Generally linear in input size."
            elif func_name in ['append', 'extend', 'insert']:
                call_complexity_val = '1'
            elif func_name in ['get', '__getitem__']:
                call_complexity_val = '1'
            elif func_name in ['keys', 'values', 'items']:
                call_complexity_val = 'n'
            elif func_name in ['add', 'remove', '__contains__']:
                call_complexity_val = '1'
            elif func_name in ['combinations', 'permutations', 'product']:
                call_complexity_val = 'n^r'
                suggestion = "Combinatorial functions can be expensive."
            elif func_name in ['math.pow', 'math.log', 'math.exp', 'math.sqrt']:
                call_complexity_val = '1'
            elif func_name in ['bisect_left', 'bisect_right', 'heapq.heappush', 'heapq.heappop']:
                call_complexity_val = 'log n'

            call_info = {
                'type': 'call',
                'func': func_name,
                'line': node.lineno,
                'complexity': call_complexity_val,
                'suggestion': suggestion
            }
            self._update_function_complexity(call_complexity_val, call_info)
        self.generic_visit(node)

    def _update_function_complexity(self, new_complexity, component_info, condition=None):
        if self.current_function:
            current_complexity_str, components = self.function_complexity[self.current_function]
            if current_complexity_str == "O(1)":
                self.function_complexity[self.current_function] = (f"O({new_complexity})", components + [component_info])
            elif current_complexity_str == f"O({new_complexity})":
                self.function_complexity[self.current_function] = (current_complexity_str, components + [component_info])
            elif current_complexity_str.startswith("O(n") and new_complexity == "n":
                power = 1
                if '^' in current_complexity_str:
                    try:
                        power = int(current_complexity_str.split('^')[1][:-1])
                    except ValueError:
                        pass
                self.function_complexity[self.current_function] = (f"O(n^{power + 1})", components + [component_info])
            elif current_complexity_str.startswith("O(n") and new_complexity == "log n":
                self.function_complexity[self.current_function] = (f"{current_complexity_str.split(')')[0]} log n)", components + [component_info])
            elif current_complexity_str == "O(log n)" and new_complexity == "n":
                self.function_complexity[self.current_function] = ("O(n log n)", components + [component_info])
            elif new_complexity == "n" and current_complexity_str == "O(1)":
                self.function_complexity[self.current_function] = ("O(n)", components + [component_info])
            elif new_complexity == "log n" and current_complexity_str == "O(1)":
                self.function_complexity[self.current_function] = ("O(log n)", components + [component_info])
            elif new_complexity == "n log n" and current_complexity_str == "O(n)":
                self.function_complexity[self.current_function] = ("O(n log n)", components + [component_info])
            elif new_complexity == "n log n" and current_complexity_str == "O(log n)":
                self.function_complexity[self.current_function] = ("O(n log n)", components + [component_info])
            elif new_complexity == "n log n" and current_complexity_str == "O(1)":
                self.function_complexity[self.current_function] = ("O(n log n)", components + [component_info])
            elif new_complexity != "1" and current_complexity_str == "O(1)":
                self.function_complexity[self.current_function] = (f"O({new_complexity})", components + [component_info])

    def visit_ListComp(self, node):
        if self.current_function:
            self.space_complexity[self.current_function] = self._update_space_complexity(self.space_complexity[self.current_function], "n")
        self.generic_visit(node)

    def visit_DictComp(self, node):
        if self.current_function:
            self.space_complexity[self.current_function] = self._update_space_complexity(self.space_complexity[self.current_function], "n")
        self.generic_visit(node)

    def visit_SetComp(self, node):
        if self.current_function:
            self.space_complexity[self.current_function] = self._update_space_complexity(self.space_complexity[self.current_function], "n")
        self.generic_visit(node)

    def visit_GeneratorExp(self, node):
        self.generic_visit(node)

    def visit_Name(self, node):
        if self.current_function and isinstance(node.ctx, ast.Store):
            self.space_complexity[self.current_function] = self._update_space_complexity(self.space_complexity[self.current_function], "1")
        self.generic_visit(node)

    def visit_List(self, node):
        if self.current_function:
            self.space_complexity[self.current_function] = self._update_space_complexity(self.space_complexity[self.current_function], "n")
        self.generic_visit(node)

    def visit_Dict(self, node):
        if self.current_function:
            self.space_complexity[self.current_function] = self._update_space_complexity(self.space_complexity[self.current_function], "n")
        self.generic_visit(node)

    def visit_Set(self, node):
        if self.current_function:
            self.space_complexity[self.current_function] = self._update_space_complexity(self.space_complexity[self.current_function], "n")
        self.generic_visit(node)

    def _update_space_complexity(self, current_complexity, new_term):
        if current_complexity == "O(1)":
            return f"O({new_term})"
        elif new_term == "1":
            return current_complexity
        elif current_complexity == f"O({new_term})":
            return current_complexity
        elif current_complexity.startswith("O(n") or new_term == "n":
            return "O(n)"
        elif current_complexity.startswith("O(log n)") and new_term == "n":
            return "O(n)"
        elif current_complexity == "O(n)" and new_term == "log n":
            return "O(n)"
        elif current_complexity.startswith("O(n)") and new_term.startswith("log n"):
            return "O(n log n)"
        elif current_complexity.startswith("O(log n)") and new_term.startswith("O(log n)"):
            return "O(log n)"
        else:
            return f"O({current_complexity.split('(')[1][:-1]} + {new_term})"

def analyze_python_code(filename):
    try:
        with open(filename, 'r') as f:
            code = f.read()
    except FileNotFoundError:
        return f"Error: File '{filename}' not found."

    tree = ast.parse(code)
    base, ext = os.path.splitext(filename)
    ast_filename = f"ast_tree_{base}{ext}.txt"

    with open(ast_filename, "w") as f:
        f.write(ast.dump(tree, indent=4))
    print(f"Abstract Syntax Tree (AST) saved to '{ast_filename}'")

    defined_names = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            defined_names.add(node.name)
        elif isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store):
            defined_names.add(node.id)

    used_names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load):
            used_names.add(node.id)
        elif isinstance(node, (ast.Call, ast.Attribute)):
            if hasattr(node, 'func'):
                if isinstance(node.func, ast.Name):
                    used_names.add(node.func.id)
                elif isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Name):
                    used_names.add(node.func.value.id)

    unused = defined_names - used_names
    unused_vars_funcs = {name for name in unused if name not in [mod.module.split('.')[0] for mod in tree.body if isinstance(mod, ast.ImportFrom)]}
    imported_names = set()
    for node in tree.body:
        if isinstance(node, ast.Import):
            for alias in node.names:
                imported_names.add(alias.name.split('.')[0])
        elif isinstance(node, ast.ImportFrom):
            imported_names.add(node.module.split('.')[0])

    used_imports = set()
    for name in used_names:
        if name in imported_names:
            used_imports.add(name)

    unused_imports = imported_names - used_imports

    complexity_analyzer = PythonComplexityAnalyzer()
    complexity_analyzer.visit(tree)

    complexity_report = {}
    for func, (complexity_str, components) in complexity_analyzer.function_complexity.items():
        details = []
        for comp in components:
            if comp['type'] in ('for', 'while'):
                details.append({
                    'type': 'loop',
                    'location': f"{comp['type']} loop at line {comp['line']}",
                    'detail': f"iterates over {comp.get('iter', '?')}",
                    'complexity': 'O(n)' if comp['nested_level'] == 1 else f"O(n^{comp['nested_level']})",
                    'suggestion': "Nested loops can lead to polynomial complexity - consider alternatives" if comp['nested_level'] > 1 else None
                })
            elif comp['type'] == 'call':
                details.append({
                    'type': 'call',
                    'location': f"call to {comp['func']}() at line {comp['line']}",
                    'complexity': f"O({comp['complexity']})",
                    'suggestion': comp['suggestion']
                })

        complexity_report[func] = {
            'time_complexity': complexity_str,
            'space_complexity': complexity_analyzer.space_complexity.get(func, "O(1)"),
            'components': details
        }

    return {
        "unused_imports": list(unused_imports),
        "unused_variables_functions": list(unused_vars_funcs),
        "complexity": complexity_report,
        "original_code": code
    }

def remove_unused_python_code(code, unused_imports, unused_variables_functions):
    tree = ast.parse(code)
    new_body = []
    defined_in_scope = set()

    for node in tree.body:
        keep_node = True
        if isinstance(node, ast.Import):
            node.names = [alias for alias in node.names if alias.name.split('.')[0] not in unused_imports]
            if not node.names:
                keep_node = False
        elif isinstance(node, ast.ImportFrom):
            if node.module and node.module.split('.')[0] in unused_imports:
                keep_node = False
        elif isinstance(node, (ast.FunctionDef, ast.ClassDef, ast.Assign)):
            node_names = []
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
                node_names.append(node.name)
            elif isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name):
                        node_names.append(target.id)

            for name in node_names:
                if name in unused_variables_functions:
                    keep_node = False
                    break

        if keep_node:
            new_body.append(node)
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
                defined_in_scope.add(node.name)
            elif isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name):
                        defined_in_scope.add(target.id)

    new_tree = ast.Module(body=new_body, type_ignores=[])
    ast.fix_missing_locations(new_tree)
    optimized_code = ast.unparse(new_tree)
    return optimized_code

def suggest_python_secure_coding(code):
    suggestions = []
    tree = ast.parse(code)

    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == 'input':
            suggestions.append({
                "type": "security",
                "location": f"Input function used at line {node.lineno}",
                "suggestion": "Sanitize and validate user input to prevent injection vulnerabilities."
            })
        elif isinstance(node, ast.Call) and (
            (isinstance(node.func, ast.Name) and node.func.id in ['eval', 'exec']) or
            (isinstance(node.func, ast.Attribute) and node.func.attr in ['eval', 'exec'])
        ):
            suggestions.append({
                "type": "security",
                "location": f"Potentially unsafe function call (`{ast.unparse(node.func)}`) at line {node.lineno}",
                "suggestion": "Avoid using `eval()` and `exec()` as they can execute arbitrary code."
            })
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == 'open':
            if len(node.args) > 0 and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                if node.args[0].value.startswith('/'):
                    suggestions.append({
                        "type": "security",
                        "location": f"File operation with absolute path at line {node.lineno}",
                        "suggestion": "Consider using relative paths or managing paths more carefully."
                    })
        elif isinstance(node, ast.Import) or isinstance(node, ast.ImportFrom):
            for alias in node.names:
                if alias.name in ['pickle', 'marshal', 'shelve']:
                    suggestions.append({
                        "type": "security",
                        "location": f"Import of potentially unsafe module `{alias.name}` at line {node.lineno}",
                        "suggestion": "Be cautious when loading data from untrusted sources."
                    })

    return suggestions

